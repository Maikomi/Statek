using UnityEngine;
using UnityEngine.InputSystem;

public class ShipMovement : MonoBehaviour
{
    [Header("References")]
    [SerializeField] private SailController sailController;
    [SerializeField] private Transform sailTransform;
    [SerializeField] private Transform sailForcePoint;

    [Header("Environment")]
    [Tooltip("Global direction and magnitude of the true wind in world coordinates.")]
    [SerializeField] private Vector3 trueWindVector = new Vector3(0f, 0f, 20f);

    [Header("Square Sail Aerodynamics")]
    [Tooltip("Overall force multiplier for the sail propulsion.")]
    [SerializeField] private float sailForceMultiplier = 200f;

    [Tooltip("Multiplier for torque generated on the ship hull when the sail is angled.")]
    [SerializeField] private float windTorqueMultiplier = 0.5f;

    [Header("Hydrodynamics & Resistance")]
    [Tooltip("Forward/backward water drag (hull resistance).")]
    [SerializeField] private float forwardDrag = 0.5f;

    [Tooltip("Lateral water drag (prevents sideways drift/leeway).")]
    [SerializeField] private float lateralDrag = 5f;

    [Tooltip("Angular drag slowing down ship rotation.")]
    [SerializeField] private float angularDrag = 3f;

    [Tooltip("Mass of the ship used for linear acceleration calculation.")]
    [SerializeField] private float shipMass = 100f;

    [Tooltip("Moment of inertia of the ship used for rotational acceleration calculation.")]
    [SerializeField] private float shipInertia = 50f;

    [Header("Rudder / Steering")]
    [Tooltip("Torque applied by the manual rudder during movement.")]
    [SerializeField] private float rudderTorque = 15f;

    private Vector3 linearVelocity = Vector3.zero;
    private float angularVelocity = 0f;

    /// Gets the current linear velocity vector of the ship in world space.
    public Vector3 LinearVelocity => this.linearVelocity;

    /// Gets the current scalar speed of the ship.
    public float CurrentSpeed => this.linearVelocity.magnitude;

    private void Reset()
    {
        this.sailController = this.GetComponent<SailController>();
    }

    private void Update()
    {
        float deltaTime = Time.deltaTime;
        if (deltaTime <= 0f)
        {
            return;
        }

        // 1. Fetch sail opening percentage (0.0 to 1.0)
        float openingFactor = 1f;
        if (this.sailController != null)
        {
            openingFactor = this.sailController.Opening / 100f;
        }

        // 2. Calculate Apparent Wind
        Vector3 apparentWind = this.trueWindVector - this.linearVelocity;
        apparentWind.y = 0f;

        float apparentWindSpeed = apparentWind.magnitude;
        Vector3 totalSailForce = Vector3.zero;
        float windInducedTorque = 0f;

        if (apparentWindSpeed > 0.01f && openingFactor > 0f)
        {
            Vector3 apparentWindDir = apparentWind.normalized;

            // Determine sail forward vector
            Vector3 sailFacingDirection = this.transform.forward;
            if (this.sailTransform != null)
            {
                sailFacingDirection = this.sailTransform.forward;
            }

            // Calculate wind impact from behind
            float windAlignment = Vector3.Dot(apparentWindDir, sailFacingDirection);

            // Calculate force magnitude
            float efficiency = Mathf.Max(0.1f, windAlignment);
            float forceMagnitude = apparentWindSpeed * efficiency * openingFactor * this.sailForceMultiplier;

            totalSailForce = sailFacingDirection * forceMagnitude;

            // 3. Calculate rotational torque generated by wind force on angled sail
            Transform applicationPoint = (this.sailForcePoint != null) ? this.sailForcePoint : this.transform;
            Vector3 forceArm = applicationPoint.position - this.transform.position;

            // Torque vector = arm x force
            Vector3 torqueVector = Vector3.Cross(totalSailForce, forceArm);

            // Vertical Y torque rotates the ship left or right
            windInducedTorque = torqueVector.y * this.windTorqueMultiplier;
        }

        // 4. Update linear acceleration and velocity
        Vector3 acceleration = totalSailForce / this.shipMass;
        this.linearVelocity += acceleration * deltaTime;

        // 5. Update angular acceleration and velocity from wind torque
        float angularAcceleration = windInducedTorque / this.shipInertia;
        this.angularVelocity += angularAcceleration * deltaTime;

        // 6. Apply water resistance / hydrodynamics
        this.ApplyWaterResistance(deltaTime);

        // 7. Apply manual rudder steering input
        this.HandleSteeringInput(deltaTime);

        // 8. Update position and rotation in world space
        this.transform.position += this.linearVelocity * deltaTime;
        this.transform.Rotate(Vector3.up, this.angularVelocity * deltaTime);
    }


    /// Applies directional water drag and rotational dampening.
    private void ApplyWaterResistance(float deltaTime)
    {
        // Linear drag in local space
        Vector3 localVelocity = this.transform.InverseTransformDirection(this.linearVelocity);

        localVelocity.z -= localVelocity.z * this.forwardDrag * deltaTime;
        localVelocity.x -= localVelocity.x * this.lateralDrag * deltaTime;
        localVelocity.y = 0f;

        this.linearVelocity = this.transform.TransformDirection(localVelocity);

        // Rotational water drag
        this.angularVelocity -= this.angularVelocity * this.angularDrag * deltaTime;
    }

    private void HandleSteeringInput(float deltaTime)
    {
        if (Keyboard.current == null)
        {
            return;
        }

        float steerInput = 0f;
        if (Keyboard.current.leftArrowKey.isPressed)
        {
            steerInput -= 1f;
        }

        if (Keyboard.current.rightArrowKey.isPressed)
        {
            steerInput += 1f;
        }

        float speedFactor = Mathf.Clamp01(this.linearVelocity.magnitude / 2f);
        float torque = steerInput * this.rudderTorque * (0.2f + 0.8f * speedFactor);
        this.angularVelocity += torque * deltaTime;
    }

    private void OnDrawGizmosSelected()
    {
        Gizmos.color = Color.blue;
        Gizmos.DrawRay(this.transform.position + (Vector3.up * 2f), this.trueWindVector);

        Gizmos.color = Color.green;
        Gizmos.DrawRay(this.transform.position, this.linearVelocity);

        if (this.sailTransform != null)
        {
            Gizmos.color = Color.yellow;
            Gizmos.DrawRay(this.sailTransform.position, this.sailTransform.forward * 3f);
        }
    }
}